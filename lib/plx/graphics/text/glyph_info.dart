class GlyphInfo {
  final double u1, v1, u2, v2;
  final double width, height;
  final double left, top;
  final double advance;

  GlyphInfo({
    required this.u1,
    required this.v1,
    required this.u2,
    required this.v2,
    required this.width,
    required this.height,
    required this.left,
    required this.top,
    required this.advance,
  });
}
